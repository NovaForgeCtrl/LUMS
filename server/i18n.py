def normalize_language(language):
    if not isinstance(language, str):
        return None

    candidate = LANGUAGE_ALIASES.get(language.strip().lower(), language.strip())
    if candidate in LANGUAGES:
        return candidate

    primary = candidate.split("-", 1)[0].lower()
    return LANGUAGE_ALIASES.get(primary, primary if primary in LANGUAGES else None)


def browser_language(accept_languages):
    for language, _quality in accept_languages:
        match = normalize_language(language)
        if match is not None:
            return match
    return "de"


