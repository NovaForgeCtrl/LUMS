from server.migrations import MIGRATIONS
from server.migrations.telemetry import TELEMETRY_MIGRATION


def test_telemetry_migration_is_registered_after_infrastructure():
    versions = [migration.version for migration in MIGRATIONS]

    assert versions == [
        "001-core-schema",
        "002-security-schema",
        "003-rbac-schema",
        "004-rbac-system-roles",
        "005-infrastructure-topology",
        "006-telemetry",
        "007-package-search",
        "008-alerts",
    ]


def test_telemetry_migration_has_seven_static_statements():
    migration = TELEMETRY_MIGRATION

    assert isinstance(migration.statements, tuple)
    assert len(migration.statements) == 7
    assert len(migration.checksum) == 64

    for statement in migration.statements:
        assert isinstance(statement, str)
        assert statement.strip()
        assert "%s" not in statement
        assert "?" not in statement


def test_client_telemetry_has_all_metrics_and_timestamp_types():
    sql = TELEMETRY_MIGRATION.statements[0]

    assert "CREATE TABLE client_telemetry" in sql
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in sql
    assert "client_id BIGINT NOT NULL" in sql
    assert "recorded_at TIMESTAMPTZ NOT NULL" in sql

    for column in (
        "cpu_percent DOUBLE PRECISION NOT NULL",
        "memory_percent DOUBLE PRECISION NOT NULL",
        "memory_total_bytes BIGINT NOT NULL",
        "memory_available_bytes BIGINT NOT NULL",
        "network_rx_bytes BIGINT",
        "network_tx_bytes BIGINT",
        "disk_percent DOUBLE PRECISION",
    ):
        assert column in sql


def test_client_telemetry_checks_all_metric_ranges():
    sql = TELEMETRY_MIGRATION.statements[0]

    for constraint in (
        "ck_client_telemetry_cpu_percent",
        "ck_client_telemetry_memory_percent",
        "ck_client_telemetry_memory_total",
        "ck_client_telemetry_memory_available",
        "ck_client_telemetry_network_rx",
        "ck_client_telemetry_network_tx",
        "ck_client_telemetry_disk_percent",
    ):
        assert constraint in sql

    assert "memory_available_bytes <= memory_total_bytes" in sql
    assert "network_rx_bytes >= 0" in sql
    assert "network_tx_bytes >= 0" in sql


