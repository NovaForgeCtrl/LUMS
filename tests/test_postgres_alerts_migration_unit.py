from server.migrations import MIGRATIONS
from server.migrations.alerts import ALERTS_MIGRATION


EXPECTED_VERSIONS = [
    "001-core-schema",
    "002-security-schema",
    "003-rbac-schema",
    "004-rbac-system-roles",
    "005-infrastructure-topology",
    "006-telemetry",
    "007-package-search",
    "008-alerts",
]


def test_alerts_migration_is_registered_as_number_eight():
    versions = [migration.version for migration in MIGRATIONS]

    assert versions == EXPECTED_VERSIONS
    assert MIGRATIONS[7] is ALERTS_MIGRATION


def test_alerts_migration_has_ten_static_statements():
    migration = ALERTS_MIGRATION

    assert isinstance(migration.statements, tuple)
    assert len(migration.statements) == 10
    assert len(migration.checksum) == 64

    for statement in migration.statements:
        assert isinstance(statement, str)
        assert statement.strip()
        assert "?" not in statement
        assert "%s" not in statement


