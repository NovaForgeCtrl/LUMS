def test_alert_indexes_support_active_history_and_notification_queries():
    statements = ALERTS_MIGRATION.statements

    assert "idx_alerts_status_triggered_at" in statements[5]
    assert (
        "ON alerts (status, triggered_at DESC)"
        in statements[5]
    )

    assert "idx_alerts_triggered_at" in statements[6]
    assert "ON alerts (triggered_at DESC)" in statements[6]

    assert "idx_alert_history_alert_id_id" in statements[7]
    assert "ON alert_history (alert_id, id)" in statements[7]

    assert "idx_alert_notifications_alert_sent" in statements[8]
    assert (
        "ON alert_notifications_log (alert_id, sent_at DESC)"
        in statements[8]
    )

    assert "idx_alert_notifications_integration_sent" in statements[9]
    assert (
        "ON alert_notifications_log (integration_id, sent_at DESC)"
        in statements[9]
    )


