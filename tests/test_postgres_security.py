@dataclass(frozen=True)
class PostgresEnvironment:
    # Never expose connection credentials in pytest fixture representations.
    database_url: str = field(repr=False)
    schema_name: str


class FakeConnection:
    def __init__(self):
        self.closed = False
        self.autocommit = True
        self.info = SimpleNamespace(
            transaction_status=TransactionStatus.IDLE
        )


@pytest.fixture
def postgres_environment():
    database_url = require_test_database_url()

    admin = psycopg.connect(
        database_url,
        autocommit=True,
        row_factory=dict_row,
        application_name="lums-postgres-security-test-setup",
    )
    schema_name = f"lums_security_test_{uuid4().hex}"
    schema_created = False

    try:
        identity = admin.execute(
            "SELECT current_database(), current_user"
        ).fetchone()

        if (
            identity["current_database"] != "lums_integration"
            or identity["current_user"] != "lums_pg_bootstrap"
        ):
            pytest.fail(
                "Refusing security tests outside the dedicated "
                "lums_integration database and lums_pg_bootstrap role."
            )

        admin.execute(
            sql.SQL("CREATE SCHEMA {}").format(
                sql.Identifier(schema_name)
            )
        )
        schema_created = True

        setup = psycopg.connect(
            database_url,
            autocommit=True,
            row_factory=dict_row,
            application_name="lums-postgres-security-test-schema",
        )
        try:
            setup.execute(
                sql.SQL("SET search_path TO {}").format(
                    sql.Identifier(schema_name)
                )
            )
            setup.execute(
                """
                CREATE TABLE login_rate_limits (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    rate_limit_key TEXT NOT NULL,
                    username TEXT NOT NULL,
                    failed_attempts INTEGER NOT NULL DEFAULT 0,
                    first_failed_at TEXT NOT NULL,
                    last_failed_at TEXT NOT NULL,
                    locked_until TEXT,
                    CONSTRAINT uq_login_rate_limits_key
                        UNIQUE (rate_limit_key)
                )
                """
            )
        finally:
            run_cleanup(("close setup connection", setup.close))

        yield PostgresEnvironment(database_url, schema_name)

    finally:
        run_cleanup(
            (
                "drop test schema",
                lambda: admin.execute(
                    sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(
                        sql.Identifier(schema_name)
                    )
                ) if schema_created else None,
            ),
            ("close admin connection", admin.close),
        )


def open_connection(database_url, schema_name, application_name):
    connection = psycopg.connect(
        database_url,
        autocommit=True,
        row_factory=dict_row,
        application_name=application_name,
    )
    try:
        connection.execute(
            sql.SQL("SET search_path TO {}").format(
                sql.Identifier(schema_name)
            )
        )
    except BaseException:
        run_cleanup(("close connection after search_path failure", connection.close))
        raise

    return connection


def test_record_login_failure_requires_caller_transaction():
    with pytest.raises(DatabaseTransactionStateError):
        record_login_failure(
            FakeConnection(),
            "admin|127.0.0.1",
            "admin",
        )


@pytest.mark.parametrize(
    "rate_limit_key,username",
    [
        ("", "admin"),
        ("admin|127.0.0.1", "bad\x00name"),
    ],
)
def test_record_login_failure_rejects_invalid_input(
    postgres_environment,
    rate_limit_key,
    username,
):
    database_url = postgres_environment.database_url
    schema_name = postgres_environment.schema_name
    connection = open_connection(
        database_url, schema_name, "lums-security-invalid-input-test"
    )
    try:
        with transaction(connection):
            with pytest.raises(ValueError):
                record_login_failure(
                    connection, rate_limit_key, username
                )
    finally:
        run_cleanup(("close PostgreSQL test connection", connection.close))


def test_record_login_failure_applies_escalating_lock_steps(
    postgres_environment,
):
    database_url = postgres_environment.database_url
    schema_name = postgres_environment.schema_name
    connection = open_connection(
        database_url, schema_name, "lums-security-escalation-test"
    )

    try:
        first_failed_at = None

        for expected_attempt in range(1, 9):
            before = datetime.now(timezone.utc)

            with transaction(connection):
                failed_attempts, locked_until = record_login_failure(
                    connection,
                    "admin|127.0.0.1",
                    "admin",
                )

            assert failed_attempts == expected_attempt

            if expected_attempt == 1:
                first_failed_at = connection.execute(
                    """
                    SELECT first_failed_at
                    FROM login_rate_limits
                    WHERE rate_limit_key = %s
                    """,
                    ("admin|127.0.0.1",),
                ).fetchone()["first_failed_at"]

            if expected_attempt < 5:
                assert locked_until is None
            else:
                expected_seconds = {
                    5: 30,
                    6: 60,
                    7: 120,
                }.get(expected_attempt, 300)

                remaining = (
                    datetime.fromisoformat(locked_until) - before
                ).total_seconds()

                assert expected_seconds - 2 <= remaining <= expected_seconds + 2

        stored = connection.execute(
            """
            SELECT failed_attempts, first_failed_at, last_failed_at,
                   locked_until, username
            FROM login_rate_limits
            WHERE rate_limit_key = %s
            """,
            ("admin|127.0.0.1",),
        ).fetchone()

        assert stored["failed_attempts"] == 8
        assert stored["first_failed_at"] == first_failed_at
        assert stored["last_failed_at"] is not None
        assert stored["locked_until"] is not None
        assert stored["username"] == "admin"

    finally:
        run_cleanup(("close PostgreSQL test connection", connection.close))


def test_record_login_failure_rolls_back_with_outer_transaction(
    postgres_environment,
):
    database_url = postgres_environment.database_url
    schema_name = postgres_environment.schema_name
    connection = open_connection(
        database_url, schema_name, "lums-security-rollback-test"
    )

    try:
        with pytest.raises(RuntimeError, match="force rollback"):
            with transaction(connection):
                record_login_failure(
                    connection,
                    "rollback|127.0.0.1",
                    "rollback-user",
                )
                raise RuntimeError("force rollback")

        row = connection.execute(
            """
            SELECT COUNT(*) AS total
            FROM login_rate_limits
            WHERE rate_limit_key = %s
            """,
            ("rollback|127.0.0.1",),
        ).fetchone()

        assert row["total"] == 0

    finally:
        run_cleanup(("close PostgreSQL test connection", connection.close))


def test_record_login_failure_increments_concurrently_without_lost_updates(
    postgres_environment,
):
    database_url = postgres_environment.database_url
    schema_name = postgres_environment.schema_name
    workers = 12
    start = Barrier(workers)

    def increment(index):
        connection = open_connection(
            database_url,
            schema_name,
            f"lums-security-concurrent-{index}",
        )
        try:
            start.wait(timeout=10)
            with transaction(connection):
                return record_login_failure(
                    connection,
                    "parallel|127.0.0.1",
                    "parallel-user",
                )[0]
        finally:
            run_cleanup(("close PostgreSQL test connection", connection.close))

    with ThreadPoolExecutor(max_workers=workers) as executor:
        returned_counts = list(
            executor.map(increment, range(workers))
        )

    connection = open_connection(
        database_url, schema_name, "lums-security-concurrent-check"
    )
    try:
        row = connection.execute(
            """
            SELECT failed_attempts, locked_until
            FROM login_rate_limits
            WHERE rate_limit_key = %s
            """,
            ("parallel|127.0.0.1",),
        ).fetchone()

        assert sorted(returned_counts) == list(range(1, workers + 1))
        assert row["failed_attempts"] == workers
        assert row["locked_until"] is not None

    finally:
        run_cleanup(("close PostgreSQL test connection", connection.close))


def test_rate_limit_timestamp_is_fresh_after_conflict_wait(
    postgres_environment,
):
    database_url = postgres_environment.database_url
    schema_name = postgres_environment.schema_name
    workers = 8

    blocker = open_connection(
        database_url, schema_name, "lums-security-timestamp-blocker"
    )
    observer = open_connection(
        database_url, schema_name, "lums-security-timestamp-observer"
    )

    key = "delayed-parallel|127.0.0.1"
    old_time = (
        datetime.now(timezone.utc) - timedelta(hours=1)
    ).isoformat()

    try:
        with transaction(blocker):
            blocker.execute(
                """
                INSERT INTO login_rate_limits (
                    rate_limit_key,
                    username,
                    failed_attempts,
                    first_failed_at,
                    last_failed_at,
                    locked_until
                )
                VALUES (%s, %s, 4, %s, %s, NULL)
                """,
                (key, "delayed-parallel", old_time, old_time),
            )

        start = Barrier(workers)

        def increment(index):
            connection = open_connection(
                database_url,
                schema_name,
                "lums-security-row-lock-waiter",
            )
            try:
                start.wait(timeout=10)
                with transaction(connection):
                    return record_login_failure(
                        connection, key, "delayed-parallel"
                    )[0]
            finally:
                run_cleanup(("close PostgreSQL test connection", connection.close))

        with ThreadPoolExecutor(max_workers=workers) as executor:
            with transaction(blocker):
                blocker.execute(
                    """
                    SELECT failed_attempts
                    FROM login_rate_limits
                    WHERE rate_limit_key = %s
                    FOR UPDATE
                    """,
                    (key,),
                ).fetchone()

                futures = [
                    executor.submit(increment, index)
                    for index in range(workers)
                ]

                deadline = monotonic() + 10
                waiting_count = 0

                while monotonic() < deadline:
                    row = observer.execute(
                        """
                        SELECT COUNT(*) AS total
                        FROM pg_stat_activity
                        WHERE application_name = %s
                          AND wait_event_type = 'Lock'
                        """,
                        ("lums-security-row-lock-waiter",),
                    ).fetchone()

                    waiting_count = row["total"]
                    if waiting_count >= workers:
                        break

                    sleep(0.01)

                assert waiting_count >= workers, (
                    "Not all concurrent transactions waited on the row lock."
                )

                # All worker timestamps were calculated before this delay.
                sleep(3.2)

            returned_counts = sorted(
                future.result(timeout=10)
                for future in futures
            )

        assert returned_counts == list(range(5, 5 + workers))

        stored = observer.execute(
            """
            SELECT failed_attempts, last_failed_at, locked_until
            FROM login_rate_limits
            WHERE rate_limit_key = %s
            """,
            (key,),
        ).fetchone()

        assert stored["failed_attempts"] == 4 + workers

        now = datetime.now(timezone.utc)
        last_failed_at = datetime.fromisoformat(
            stored["last_failed_at"]
        )
        locked_until = datetime.fromisoformat(
            stored["locked_until"]
        )

        assert now - last_failed_at < timedelta(seconds=2)
        assert timedelta(seconds=298) < locked_until - now < timedelta(seconds=301)

    finally:
        run_cleanup(
            ("close observer connection", observer.close),
            ("close blocker connection", blocker.close),
        )
