from server.migrations import MIGRATIONS
from server.migrations.package_search import PACKAGE_SEARCH_MIGRATION


def test_package_search_migration_is_registered_as_number_seven():
    versions = [migration.version for migration in MIGRATIONS]

    assert versions == [
        "001-core-schema",
        "002-security-schema",
        "003-rbac-schema",
        "004-rbac-system-roles",
        "005-infrastructure-topology",
        "006-telemetry",
        "007-package-search",
        "008-alerts",
    ]


def test_package_search_migration_has_three_static_statements():
    migration = PACKAGE_SEARCH_MIGRATION

    assert isinstance(migration.statements, tuple)
    assert len(migration.statements) == 3
    assert len(migration.checksum) == 64

    for statement in migration.statements:
        assert isinstance(statement, str)
        assert statement.strip()
        assert "?" not in statement
        assert "%s" not in statement


def test_package_search_table_preserves_request_fields():
    sql = PACKAGE_SEARCH_MIGRATION.statements[0]

    assert "CREATE TABLE package_search_requests" in sql
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in sql
    assert "client_id BIGINT NOT NULL" in sql
    assert "query TEXT NOT NULL" in sql
    assert "status TEXT NOT NULL" in sql
    assert "created_at TIMESTAMPTZ NOT NULL" in sql
    assert "started_at TIMESTAMPTZ" in sql
    assert "finished_at TIMESTAMPTZ" in sql
    assert "result_json JSONB" in sql
    assert "error_message TEXT" in sql


def test_package_search_query_constraints_match_input_contract():
    sql = PACKAGE_SEARCH_MIGRATION.statements[0]

    assert "ck_package_search_query" in sql
    assert "char_length(query) BETWEEN 1 AND 128" in sql
    assert "query = btrim(query)" in sql
    assert "left(query, 1) <> '-'" in sql


def test_package_search_status_constraints_preserve_state_machine():
    sql = PACKAGE_SEARCH_MIGRATION.statements[0]

    assert "ck_package_search_status" in sql
    for status in ("pending", "running", "completed", "failed"):
        assert f"'{status}'" in sql

    assert "ck_package_search_state_timestamps" in sql
    assert "started_at IS NULL" in sql
    assert "started_at IS NOT NULL" in sql
    assert "finished_at IS NULL" in sql
    assert "finished_at IS NOT NULL" in sql


def test_package_search_results_are_json_arrays():
    sql = PACKAGE_SEARCH_MIGRATION.statements[0]

    assert "ck_package_search_result_array" in sql
    assert "result_json JSONB" in sql
    assert "jsonb_typeof(result_json) = 'array'" in sql


def test_package_search_error_message_is_bounded():
    sql = PACKAGE_SEARCH_MIGRATION.statements[0]

    assert "ck_package_search_error_length" in sql
    assert "char_length(error_message) <= 1024" in sql


def test_package_search_client_foreign_key_matches_legacy_behavior():
    sql = PACKAGE_SEARCH_MIGRATION.statements[0]

    assert "fk_package_search_requests_client" in sql
    assert "FOREIGN KEY (client_id)" in sql
    assert "REFERENCES clients(id)" in sql
    assert "ON DELETE CASCADE" not in sql


def test_package_search_polling_index_preserves_order():
    sql = PACKAGE_SEARCH_MIGRATION.statements[1]

    assert "idx_package_search_client_status_id" in sql
    assert (
        "ON package_search_requests (client_id, status, id)"
        in sql
    )


def test_package_search_created_index_is_present():
    sql = PACKAGE_SEARCH_MIGRATION.statements[2]

    assert "idx_package_search_client_created" in sql
    assert (
        "ON package_search_requests (client_id, created_at)"
        in sql
    )
