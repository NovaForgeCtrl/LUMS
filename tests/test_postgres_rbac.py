def test_store_user_permissions_requires_caller_transaction():
    class FakeConnection:
        closed = False
        autocommit = True
        info = type(
            "Info",
            (),
            {"transaction_status": psycopg.pq.TransactionStatus.IDLE},
        )()

    with pytest.raises(DatabaseTransactionStateError):
        seed_system_roles(FakeConnection())




def test_seed_system_roles_is_idempotent(postgres_environment):
    connection = open_connection(
        postgres_environment,
        "lums-postgres-rbac-idempotent-seed-test",
    )

    try:
        with transaction(connection):
            acquire_rbac_write_lock(connection)
            first = seed_system_roles(connection)

        with transaction(connection):
            acquire_rbac_write_lock(connection)
            second = seed_system_roles(connection)

        assert first == second

        role_count = connection.execute(
            "SELECT COUNT(*) AS total FROM roles"
        ).fetchone()["total"]

        permission_count = connection.execute(
            "SELECT COUNT(*) AS total FROM role_permissions"
        ).fetchone()["total"]

        expected_permission_count = sum(
            len(ROLE_DEFAULT_PERMISSIONS[role])
            for role in (
                ROLE_ADMINISTRATOR,
                ROLE_OPERATOR,
                ROLE_VIEWER,
            )
        )

        assert role_count == 3
        assert permission_count == expected_permission_count

    finally:
        run_cleanup(("close PostgreSQL test connection", connection.close))
