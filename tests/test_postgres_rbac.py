@dataclass(frozen=True)
class PostgresEnvironment:
    database_url: str = field(repr=False)
    schema_name: str


@pytest.fixture
def postgres_environment():
    database_url = require_test_database_url()

    admin = psycopg.connect(
        database_url,
        autocommit=True,
        row_factory=dict_row,
        application_name="lums-postgres-rbac-test-setup",
    )

    schema_name = f"lums_postgres_rbac_{uuid4().hex}"
    schema_created = False

    try:
        identity = admin.execute(
            "SELECT current_database(), current_user"
        ).fetchone()

        if (
            identity["current_database"] != "lums_integration"
            or identity["current_user"] != "lums_pg_bootstrap"
        ):
            pytest.fail(
                "Refusing RBAC tests outside the dedicated "
                "lums_integration database and lums_pg_bootstrap role."
            )

        admin.execute(
            sql.SQL("CREATE SCHEMA {}").format(
                sql.Identifier(schema_name)
            )
        )
        schema_created = True

        setup = psycopg.connect(
            database_url,
            autocommit=True,
            row_factory=dict_row,
            application_name="lums-postgres-rbac-test-schema",
        )
        try:
            setup.execute(
                sql.SQL("SET search_path TO {}").format(
                    sql.Identifier(schema_name)
                )
            )

            setup.execute(
                """
                CREATE TABLE users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username TEXT NOT NULL UNIQUE,
                    enabled BOOLEAN NOT NULL DEFAULT TRUE,
                    role TEXT NOT NULL
                )
                """
            )

            setup.execute(
                """
                CREATE TABLE roles (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    role_key TEXT NOT NULL UNIQUE,
                    name TEXT NOT NULL,
                    description TEXT NOT NULL DEFAULT '',
                    is_system BOOLEAN NOT NULL DEFAULT FALSE,
                    is_migration BOOLEAN NOT NULL DEFAULT FALSE,
                    created_at TEXT NOT NULL,
                    updated_at TEXT NOT NULL,
                    CHECK (NOT (is_system AND is_migration)),
                    UNIQUE (id, role_key)
                )
                """
            )

            setup.execute(
                """
                CREATE TABLE role_permissions (
                    role_id BIGINT NOT NULL
                        REFERENCES roles(id) ON DELETE CASCADE,
                    permission TEXT NOT NULL,
                    PRIMARY KEY (role_id, permission)
                )
                """
            )

            setup.execute(
                """
                CREATE TABLE user_roles (
                    user_id BIGINT PRIMARY KEY
                        REFERENCES users(id) ON DELETE CASCADE,
                    role_id BIGINT NOT NULL
                        REFERENCES roles(id) ON DELETE RESTRICT,
                    assigned_at TEXT NOT NULL,
                    assigned_by BIGINT
                        REFERENCES users(id) ON DELETE SET NULL
                )
                """
            )

            setup.execute(
                """
                CREATE TABLE user_permission_overrides (
                    user_id BIGINT NOT NULL
                        REFERENCES users(id) ON DELETE CASCADE,
                    permission TEXT NOT NULL,
                    effect TEXT NOT NULL
                        CHECK (effect IN ('grant', 'deny')),
                    changed_at TEXT NOT NULL,
                    changed_by BIGINT
                        REFERENCES users(id) ON DELETE SET NULL,
                    PRIMARY KEY (user_id, permission)
                )
                """
            )
        finally:
            run_cleanup(("close setup connection", setup.close))

        yield PostgresEnvironment(database_url, schema_name)

    finally:
        run_cleanup(
            (
                "drop test schema",
                lambda: admin.execute(
                    sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(
                        sql.Identifier(schema_name)
                    )
                ) if schema_created else None,
            ),
            ("close admin connection", admin.close),
        )


def open_connection(environment, application_name):
    connection = psycopg.connect(
        environment.database_url,
        autocommit=True,
        row_factory=dict_row,
        application_name=application_name,
    )
    try:
        connection.execute(
            sql.SQL("SET search_path TO {}").format(
                sql.Identifier(environment.schema_name)
            )
        )
    except BaseException:
        run_cleanup(("close connection after search_path failure", connection.close))
        raise

    return connection


def insert_user(connection, username, role):
    return connection.execute(
        """
        INSERT INTO users (username, enabled, role)
        VALUES (%s, TRUE, %s)
        RETURNING id
        """,
        (username, role),
    ).fetchone()["id"]


def test_seed_system_roles_matches_default_permissions(
    postgres_environment,
):
    connection = open_connection(
        postgres_environment, "lums-postgres-rbac-seed-test"
    )

    try:
        with transaction(connection):
            acquire_rbac_write_lock(connection)
            role_ids = seed_system_roles(connection)

        assert set(role_ids) == {
            ROLE_ADMINISTRATOR,
            ROLE_OPERATOR,
            ROLE_VIEWER,
        }

        for role_key, role_id in role_ids.items():
            role = connection.execute(
                """
                SELECT role_key, is_system, is_migration
                FROM roles
                WHERE id = %s
                """,
                (role_id,),
            ).fetchone()

            assert role["role_key"] == "system-" + role_key
            assert role["is_system"] is True
            assert role["is_migration"] is False

            permissions = {
                row["permission"]
                for row in connection.execute(
                    """
                    SELECT permission
                    FROM role_permissions
                    WHERE role_id = %s
                    """,
                    (role_id,),
                ).fetchall()
            }

            assert permissions == set(
                ROLE_DEFAULT_PERMISSIONS[role_key]
            )

        assert "permissions.manage" not in (
            ROLE_DEFAULT_PERMISSIONS[ROLE_ADMINISTRATOR]
        )

        migration_roles = connection.execute(
            "SELECT COUNT(*) AS total FROM roles WHERE is_migration IS TRUE"
        ).fetchone()["total"]
        assert migration_roles == 0

    finally:
        run_cleanup(("close PostgreSQL test connection", connection.close))


def test_store_and_resolve_permissions_with_grants_and_denies(
    postgres_environment,
):
    connection = open_connection(
        postgres_environment, "lums-postgres-rbac-overrides-test"
    )

    try:
        with transaction(connection):
            acquire_rbac_write_lock(connection)
            seed_system_roles(connection)
            admin_id = insert_user(
                connection, "admin-one", ROLE_ADMINISTRATOR
            )
            operator_id = insert_user(
                connection, "operator-one", ROLE_OPERATOR
            )

            store_user_permissions(
                connection,
                admin_id,
                ROLE_ADMINISTRATOR,
                sorted(ROLE_DEFAULT_PERMISSIONS[ROLE_ADMINISTRATOR]),
            )

            selected = {
                "clients.view",
                "software.view",
                "alerts.view",
            }
            store_user_permissions(
                connection,
                operator_id,
                ROLE_OPERATOR,
                sorted(selected),
            )

        assert resolve_user_permissions(
            connection, admin_id
        ) == frozenset(ROLE_DEFAULT_PERMISSIONS[ROLE_ADMINISTRATOR])

        assert resolve_user_permissions(
            connection, operator_id
        ) == frozenset(selected)

        overrides = {
            (row["permission"], row["effect"])
            for row in connection.execute(
                """
                SELECT permission, effect
                FROM user_permission_overrides
                WHERE user_id = %s
                """,
                (operator_id,),
            ).fetchall()
        }

        assert overrides == {
            ("alerts.view", "grant"),
            ("jobs.manage", "deny"),
            ("packages.search", "deny"),
            ("updates.view", "deny"),
        }

    finally:
        run_cleanup(("close PostgreSQL test connection", connection.close))


def test_initial_bootstrap_grants_delegation_only_to_first_admin(
    postgres_environment,
):
    connection = open_connection(
        postgres_environment, "lums-postgres-rbac-bootstrap-test"
    )

    try:
        with transaction(connection):
            acquire_rbac_write_lock(connection)
            seed_system_roles(connection)
            first_admin_id = insert_user(
                connection, "first-admin", ROLE_ADMINISTRATOR
            )
            store_user_permissions(
                connection,
                first_admin_id,
                ROLE_ADMINISTRATOR,
                sorted(ROLE_DEFAULT_PERMISSIONS[ROLE_ADMINISTRATOR]),
            )

            granted = grant_initial_permission_manager(
                connection, first_admin_id
            )
            assert granted is True

            first_permissions = resolve_user_permissions(
                connection, first_admin_id
            )
            assert "permissions.manage" in first_permissions

        with transaction(connection):
            acquire_rbac_write_lock(connection)
            second_admin_id = insert_user(
                connection, "second-admin", ROLE_ADMINISTRATOR
            )
            store_user_permissions(
                connection,
                second_admin_id,
                ROLE_ADMINISTRATOR,
                sorted(ROLE_DEFAULT_PERMISSIONS[ROLE_ADMINISTRATOR]),
            )

        assert "permissions.manage" not in resolve_user_permissions(
            connection, second_admin_id
        )

        with transaction(connection):
            acquire_rbac_write_lock(connection)
            with pytest.raises(
                PostgresRBACError,
                match="exactly one user",
            ):
                grant_initial_permission_manager(
                    connection, second_admin_id
                )

    finally:
        run_cleanup(("close PostgreSQL test connection", connection.close))


