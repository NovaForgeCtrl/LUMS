"""PostgreSQL integration tests for the central migration runner.

Requires the explicit LUMS_TEST_DATABASE_URL environment variable.
Tests create and remove only their own randomly named schema.
"""

from pathlib import Path
import sys
from threading import Thread
from time import monotonic, sleep
from uuid import uuid4

import psycopg
from postgres_test_support import require_test_database_url, run_cleanup
import pytest
from psycopg import sql
from psycopg.rows import dict_row


SERVER_DIR = Path(__file__).resolve().parents[1] / "server"
if str(SERVER_DIR) not in sys.path:
    sys.path.insert(0, str(SERVER_DIR))

from migration_runner import (
    Migration,
    MigrationHistoryError,
    run_migrations,
)


LOCK_CLASS = 1_280_131_411
LOCK_OBJECT = 1
LOCK_WORKER_APP = "lums-migration-lock-worker"


@pytest.fixture
def postgres_environment():
    database_url = require_test_database_url()

    admin = psycopg.connect(
        database_url,
        autocommit=True,
        row_factory=dict_row,
        application_name="lums-migration-test-setup",
    )

    connection = None
    schema_name = f"lums_migration_test_{uuid4().hex}"
    schema_created = False

    try:
        identity = admin.execute(
            "SELECT current_database(), current_user"
        ).fetchone()

        if (
            identity["current_database"] != "lums_integration"
            or identity["current_user"] != "lums_pg_bootstrap"
        ):
            pytest.fail(
                "Refusing integration tests outside the dedicated "
                "lums_integration database and lums_pg_bootstrap role."
            )

        admin.execute(
            sql.SQL("CREATE SCHEMA {}").format(
                sql.Identifier(schema_name)
            )
        )
        schema_created = True

        connection = psycopg.connect(
            database_url,
            autocommit=True,
            row_factory=dict_row,
            application_name="lums-migration-test",
        )

        connection.execute(
            sql.SQL("SET search_path TO {}").format(
                sql.Identifier(schema_name)
            )
        )

        yield connection, database_url, schema_name

    finally:
        run_cleanup(
            (
                "close test connection",
                lambda: connection.close() if connection is not None else None,
            ),
            (
                "drop test schema",
                lambda: admin.execute(
                    sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(
                        sql.Identifier(schema_name)
                    )
                ) if schema_created else None,
            ),
            ("close admin connection", admin.close),
        )


def make_migration(version, statements):
    return Migration(
        version=version,
        description=f"Integration test {version}",
        statements=statements,
    )


def test_runner_applies_migration_and_records_history(
    postgres_environment,
):
    connection, _, _ = postgres_environment

    migration = make_migration(
        "001-integration-probe",
        (
            """
            CREATE TABLE migration_probe (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                value TEXT NOT NULL
            )
            """,
            "INSERT INTO migration_probe(value) VALUES ('persisted')",
        ),
    )

    result = run_migrations(connection, (migration,))

    assert result.applied == ("001-integration-probe",)
    assert result.already_applied == ()

    stored = connection.execute(
        "SELECT value FROM migration_probe"
    ).fetchone()
    assert stored["value"] == "persisted"

    history = connection.execute(
        """
        SELECT version, checksum, description
        FROM schema_migrations
        """
    ).fetchone()

    assert history["version"] == migration.version
    assert history["checksum"] == migration.checksum
    assert history["description"] == migration.description


def test_runner_does_not_apply_migration_twice(
    postgres_environment,
):
    connection, _, _ = postgres_environment

    migration = make_migration(
        "001-integration-once",
        (
            "CREATE TABLE migration_once (value INTEGER NOT NULL)",
            "INSERT INTO migration_once(value) VALUES (1)",
        ),
    )

    first = run_migrations(connection, (migration,))
    second = run_migrations(connection, (migration,))

    assert first.applied == ("001-integration-once",)
    assert second.applied == ()
    assert second.already_applied == ("001-integration-once",)

    count = connection.execute(
        "SELECT COUNT(*) AS count FROM migration_once"
    ).fetchone()
    assert count["count"] == 1


def test_failed_migration_rolls_back_its_schema_and_history(
    postgres_environment,
):
    connection, _, _ = postgres_environment

    migration = make_migration(
        "001-integration-failure",
        (
            "CREATE TABLE migration_must_rollback (value INTEGER)",
            "INSERT INTO missing_migration_table(value) VALUES (1)",
        ),
    )

    with pytest.raises(psycopg.errors.UndefinedTable):
        run_migrations(connection, (migration,))

    assert connection.info.transaction_status.name == "IDLE"

    table = connection.execute(
        "SELECT to_regclass('migration_must_rollback') AS relation"
    ).fetchone()
    assert table["relation"] is None

    history_count = connection.execute(
        """
        SELECT COUNT(*) AS count
        FROM schema_migrations
        WHERE version = %s
        """,
        (migration.version,),
    ).fetchone()

    assert history_count["count"] == 0


def test_runner_rejects_changed_checksum_for_applied_migration(
    postgres_environment,
):
    connection, _, _ = postgres_environment

