def test_relation_endpoints_require_exactly_one_reference():
    sql = INFRASTRUCTURE_TOPOLOGY_MIGRATION.statements[1]

    assert "ck_infrastructure_relations_source_endpoint" in sql
    assert "ck_infrastructure_relations_target_endpoint" in sql

    assert "source_node_id IS NOT NULL" in sql
    assert "source_client_id IS NOT NULL" in sql
    assert "target_node_id IS NOT NULL" in sql
    assert "target_client_id IS NOT NULL" in sql


def test_relation_schema_rejects_self_relationships():
    sql = INFRASTRUCTURE_TOPOLOGY_MIGRATION.statements[1]

    assert "ck_infrastructure_relations_no_self_node" in sql
    assert "source_node_id <> target_node_id" in sql

    assert "ck_infrastructure_relations_no_self_client" in sql
    assert "source_client_id <> target_client_id" in sql


def test_infrastructure_foreign_keys_preserve_delete_behaviour():
    nodes = INFRASTRUCTURE_TOPOLOGY_MIGRATION.statements[0]
    relations = INFRASTRUCTURE_TOPOLOGY_MIGRATION.statements[1]

    assert "REFERENCES users(id)" in nodes
    assert "ON DELETE SET NULL" in nodes

    assert "REFERENCES infrastructure_nodes(id)" in relations
    assert "REFERENCES clients(id)" in relations
    assert "REFERENCES users(id)" in relations
    assert relations.count("ON DELETE CASCADE") == 4
    assert relations.count("ON DELETE SET NULL") == 1


def test_infrastructure_relation_lookup_indexes_are_created():
    source_index = INFRASTRUCTURE_TOPOLOGY_MIGRATION.statements[2]
    target_index = INFRASTRUCTURE_TOPOLOGY_MIGRATION.statements[3]

    assert "idx_infrastructure_relations_source" in source_index
    assert "source_node_id" in source_index
    assert "source_client_id" in source_index
    assert "relation_type" in source_index

    assert "idx_infrastructure_relations_target" in target_index
    assert "target_node_id" in target_index
    assert "target_client_id" in target_index
    assert "relation_type" in target_index


def test_all_four_endpoint_combinations_have_unique_indexes():
    expected = {
        "uq_infrastructure_relations_node_node_type": (
            "source_node_id",
            "target_node_id",
        ),
        "uq_infrastructure_relations_node_client_type": (
            "source_node_id",
            "target_client_id",
        ),
        "uq_infrastructure_relations_client_node_type": (
            "source_client_id",
            "target_node_id",
        ),
        "uq_infrastructure_relations_client_client_type": (
            "source_client_id",
            "target_client_id",
        ),
    }

    statements = INFRASTRUCTURE_TOPOLOGY_MIGRATION.statements[4:]
    assert len(statements) == 4

    for statement, (index_name, columns) in zip(
        statements,
        expected.items(),
    ):
        assert f"CREATE UNIQUE INDEX {index_name}" in statement
        for column in columns:
            assert column in statement
        assert "relation_type" in statement
        assert "WHERE" in statement
        assert "IS NOT NULL" in statement


