from server.migrations import MIGRATIONS
from server.migrations.infrastructure_topology import (
    INFRASTRUCTURE_TOPOLOGY_MIGRATION,
)


def test_infrastructure_migration_is_registered_after_rbac_seed():
    versions = [migration.version for migration in MIGRATIONS]

    assert versions[:5] == [
        "001-core-schema",
        "002-security-schema",
        "003-rbac-schema",
        "004-rbac-system-roles",
        "005-infrastructure-topology",
    ]
    assert versions[5:] == [
        "006-telemetry",
        "007-package-search",
        "008-alerts",
    ]


def test_infrastructure_migration_has_eight_static_statements():
    migration = INFRASTRUCTURE_TOPOLOGY_MIGRATION

    assert isinstance(migration.statements, tuple)
    assert len(migration.statements) == 8
    assert len(migration.checksum) == 64

    for statement in migration.statements:
        assert isinstance(statement, str)
        assert statement.strip()
        assert "%s" not in statement
        assert "?" not in statement


def test_infrastructure_nodes_schema_preserves_metadata_and_node_types():
    sql = INFRASTRUCTURE_TOPOLOGY_MIGRATION.statements[0]

    assert "CREATE TABLE infrastructure_nodes" in sql
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in sql

    for column in (
        "name TEXT NOT NULL",
        "node_type TEXT NOT NULL",
        "hostname TEXT NOT NULL DEFAULT ''",
        "ip_address TEXT NOT NULL DEFAULT ''",
        "role TEXT NOT NULL DEFAULT ''",
        "location TEXT NOT NULL DEFAULT ''",
        "notes TEXT NOT NULL DEFAULT ''",
        "created_at TEXT NOT NULL",
        "updated_at TEXT NOT NULL",
        "created_by BIGINT",
    ):
        assert column in sql

    for node_type in (
        "server",
        "vm",
        "container",
        "network_device",
        "service",
        "storage",
    ):
        assert f"'{node_type}'" in sql


