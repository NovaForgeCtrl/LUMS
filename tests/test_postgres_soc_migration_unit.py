"""Unit tests for PostgreSQL migration 009-soc-storage."""

from server.migrations import MIGRATIONS
from server.migrations.soc_storage import SOC_STORAGE_MIGRATION


EXPECTED_VERSIONS = [
    "001-core-schema",
    "002-security-schema",
    "003-rbac-schema",
    "004-rbac-system-roles",
    "005-infrastructure-topology",
    "006-telemetry",
    "007-package-search",
    "008-alerts",
    "009-soc-storage",
    "010-soc-rbac",
]


def test_soc_storage_migration_is_registered_after_alerts():
    versions = [migration.version for migration in MIGRATIONS]

    assert versions == EXPECTED_VERSIONS
    assert MIGRATIONS[-2] is SOC_STORAGE_MIGRATION


def test_soc_storage_migration_has_ten_static_statements():
    migration = SOC_STORAGE_MIGRATION

    assert migration.version == "009-soc-storage"
    assert isinstance(migration.statements, tuple)
    assert len(migration.statements) == 10
    assert len(migration.checksum) == 64

    for statement in migration.statements:
        assert isinstance(statement, str)
        assert statement.strip()
        assert "?" not in statement
        assert "%s" not in statement


