def test_soc_indexes_cover_inbox_worker_and_incident_queries():
    statements = SOC_STORAGE_MIGRATION.statements

    expected_indexes = (
        (
            "idx_soc_event_inbox_pending",
            "ON soc_event_inbox (processing_status, inbox_id)",
        ),
        (
            "idx_soc_event_inbox_agent_received",
            "ON soc_event_inbox (agent_id, received_at DESC)",
        ),
        (
            "idx_soc_event_inbox_claim_recovery",
            "ON soc_event_inbox (processing_status, claimed_at, inbox_id)",
        ),
        (
            "idx_soc_incidents_status_updated",
            "ON soc_incidents (status, updated_at DESC)",
        ),
        (
            "idx_soc_incident_evidence_reference",
            "ON soc_incident_evidence (kind, reference_id)",
        ),
    )

    for name, definition in expected_indexes:
        assert any(
            name in statement and definition in statement
            for statement in statements[5:]
        )


def test_only_incident_children_use_delete_cascade():
    statements = SOC_STORAGE_MIGRATION.statements[:5]

    assert "ON DELETE CASCADE" not in statements[0]
    assert "ON DELETE CASCADE" not in statements[1]
    assert "ON DELETE CASCADE" not in statements[2]
    assert "ON DELETE CASCADE" in statements[3]
    assert "ON DELETE CASCADE" in statements[4]
